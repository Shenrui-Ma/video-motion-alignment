"""
Improved evaluation methodology that decouples DTW alignment error from reliability metric performance.

This script runs various confidence estimation systems (different window lengths L and tolerances X) 
on the benchmarks generated by `run_all_mini_benchmarks.py`.

Key features:
- For beats in non-matching (tampered) regions: Label as "non-matching" (0)
- For beats in matching regions:
  - If DTW prediction is within Y frames of interpolated ground truth: Label as "matching" (1)
  - If DTW prediction is NOT within Y frames: Label as "non-matching" (0)

Input:
- `ground_truth.json`: Manifest of benchmarks and feature paths
- Feature files (.npy): Extracted chroma features (located using ground_truth.json)

Output:
- CSV files for each confidence system containing beat-level confidence scores and MvsN labels for multiple Y values
"""
