SR = 22050
HOP_LEN = 512

def run_all_systems_on_benchmark(bm, systems, q_feats, r_feats, q_beats, r_beats, Y_values):
    """
    Runs ALL confidence systems on a single benchmark efficiently.
    Generates ground truth labels for multiple Y (tolerance) values.
    
    Args:
        bm: Benchmark dict
        systems: List of system configs
        q_feats, r_feats: Feature arrays
        q_beats, r_beats: Beat timestamps
        Y_values: List of frame tolerances to evaluate at (e.g., [5, 10])
    
    Returns:
        Dictionary mapping system names to lists of result dicts
    """
    n_frames = q_feats.shape[1]
    C = 1 - np.dot(q_feats.T, r_feats)  # Cosine distance matrix
    
    # Pre-compute global DTW once per benchmark
    steps = np.array([[1, 1], [1, 2], [2, 1]])
    weights = np.array([2, 3, 3])
    D, wp_global = librosa.sequence.dtw(C=C, step_sizes_sigma=steps, weights_mul=weights, subseq=False)
    
    # Convert warp path to seconds for interpolation
    wp_q_sec = wp_global[:, 0] * HOP_LEN / SR
    wp_r_sec = wp_global[:, 1] * HOP_LEN / SR
    if wp_q_sec[0] > wp_q_sec[-1]:
        wp_q_sec, wp_r_sec = wp_q_sec[::-1], wp_r_sec[::-1]
    
    # Convert Y values from frames to seconds
    Y_sec = {Y: Y * HOP_LEN / SR for Y in Y_values}
    
    # Process all systems efficiently
    results = {s['name']: [] for s in systems}
    tampered_frames = bm['tampered_region_frames']
    tampered_match = bm.get('tampered_match', False)
    
    def is_non_matching(t_sec):
        f_idx = int(t_sec * SR / HOP_LEN)
        if tampered_frames:
            if tampered_frames[0] <= f_idx < tampered_frames[1]:
                return not tampered_match
            else:
                return tampered_match
        return False

    duration_q = n_frames * HOP_LEN / SR
    eval_times_list = []
    # Matching regions: use query beats
    if q_beats is not None:
        for b in q_beats:
            if 0 <= b < duration_q and not is_non_matching(b):
                eval_times_list.append(b)
    
    # Non-matching regions: use 0.25s intervals
    for t in np.arange(0, duration_q, 0.25):
        if is_non_matching(t):
            eval_times_list.append(t)
    
    eval_times = sorted(list(set(eval_times_list)))
    musical_end = max(q_beats) if (q_beats is not None and len(q_beats) > 0) else 0

    for s in systems:
        L = s.get('L', 300)
        hop_ratio = s.get('hop_ratio', 1)
        X = s.get('X', 0)
        hop = L // hop_ratio
        
        # Collect % agreement scores for this system
        agreements_list = [[] for _ in range(n_frames)]
        
        # Define window start indices, ensuring the final window (ending at n_frames) is included
        starts = list(range(0, n_frames - L + 1, hop))
        if n_frames >= L and (len(starts) == 0 or starts[-1] < n_frames - L):
            starts.append(n_frames - L)
        
        for q_start in starts:
            q_end = q_start + L
            
            # Compute DTW sub-rectangle score
            mask = (wp_global[:, 0] >= q_start) & (wp_global[:, 0] <= q_end)
            rel_wp = wp_global[mask]
            if len(rel_wp) > 0:
                r_start, r_end = int(np.min(rel_wp[:, 1])), int(np.max(rel_wp[:, 1]))
                wp_flex = run_flex_dtw_on_subrectangle(C, (q_start, q_end), (r_start, r_end))
                
                if len(wp_flex) > 0:
                    # Compute % agreement for this sub-rectangle
                    pa = compute_percent_agreement(wp_global, wp_flex, q_start, q_end, X)
                    # Assign agreement score to all frames in this range
                    for frame_idx in range(max(0, q_start), min(n_frames, q_end + 1)):
                        agreements_list[frame_idx].append(pa)
        
        # Compute % agreement for each frame (median of scores from overlapping windows)
        confidences = np.zeros(n_frames)
        for i in range(n_frames):
            if len(agreements_list[i]) > 0:
                confidences[i] = np.median(agreements_list[i])
            else:
                confidences[i] = 0.0

        # Generate results for each evaluation point
        for q_time in eval_times:
            # Determine if we're in a tampered (non-matching) region
            is_in_tampered_region = is_non_matching(q_time)
            
            # Get ground truth alignment for this beat
            r_time_gt = get_gt_reference_time(q_time, q_beats, r_beats)
            
            # Compute alignment error and determine frame_idx
            if r_time_gt != np.inf:
                error, closest_q_time = compute_orthogonal_error(q_time, r_time_gt, wp_q_sec, wp_r_sec)
                frame_idx = int(closest_q_time * SR / HOP_LEN)
            else:
                error = np.inf
                frame_idx = int(q_time * SR / HOP_LEN)

            if frame_idx >= n_frames:
                continue
            
            # Compute distances from boundaries
            dist_from_beg = q_time
            dist_from_end = (n_frames * HOP_LEN / SR) - q_time
            dist_from_boundary = np.inf
            if tampered_frames:
                b1 = tampered_frames[0] * HOP_LEN / SR
                b2 = tampered_frames[1] * HOP_LEN / SR
                dist_from_boundary = min(abs(q_time - b1), abs(q_time - b2))

            # Build result dict with MvsN labels for each Y value
            result_dict = {
                "ID": bm['pair_id'],
                "Beat": q_time,
                "Confidence": confidences[frame_idx],
                "AlignmentError": error,
                "dist_from_boundary": dist_from_boundary,
                "dist_from_beg": dist_from_beg,
                "dist_from_end": dist_from_end,
                "InTamperedRegion": int(is_in_tampered_region)
            }
            
            is_unverifiable = (not is_in_tampered_region) and (q_time > musical_end)
            if is_unverifiable:
                continue
            else:
                # Add MvsN label for each Y value
                for Y in Y_values:
                    if is_in_tampered_region:
                        # Non-matching region: always label as non-matching
                        MvsN = 0
                    else:
                        # Matching region: check if DTW is close to ground truth
                        if r_time_gt == np.inf or error == np.inf:
                            # Cannot determine - label as non-matching (unreliable)
                            MvsN = 0
                        elif error <= Y_sec[Y]:
                            # DTW is close to ground truth within tolerance
                            MvsN = 1
                        else:
                            # DTW is far from ground truth - misalignment
                            MvsN = 0
                    
                    result_dict[f"MvsN_Y{Y}"] = MvsN
                
            results[s['name']].append(result_dict)
            
    return results

def process_benchmark_wrapper(args):
    bm, systems, Y_values = args
    from benchmarks.tamper_query import load_beats
    try:
        # Reconstruct relative paths from pair_id
        parts = bm['pair_id'].split('_vs_')
        q_name_raw = "_".join(parts[0].split('_')[2:]) + ".wav"
        r_name_raw = parts[1] + ".wav"
        
        q_mazurka = "_".join(q_name_raw.split('_')[:2])
        r_mazurka = "_".join(r_name_raw.split('_')[:2])
        
        q_rel_path = f"{q_mazurka}/{q_name_raw}"
        r_rel_path = f"{r_mazurka}/{r_name_raw}"

        time_shift = bm.get('time_shift_seconds', 0.0)

        q_beats = load_beats(q_rel_path)
        r_beats = load_beats(r_rel_path)

        # if q_beats is not None:
        #     q_max = q_beats[-1]
        #     q_beats = q_beats[q_beats <= q_max]
            
        # if r_beats is not None:
        #     r_max = r_beats[-1]
        #     r_beats = r_beats[r_beats <= r_max]

        if q_beats is not None and time_shift != 0:
            q_beats = q_beats + time_shift
        
        q_feat = np.load(bm['q_feat_path'])
        r_feat = np.load(bm['r_feat_path'])
        
        return run_all_systems_on_benchmark(bm, systems, q_feat, r_feat, q_beats, r_beats, Y_values)
    except Exception as e:
        print(f"[ERROR] Failed to process {bm['pair_id']}: {e}")
        return {s['name']: [] for s in systems}

